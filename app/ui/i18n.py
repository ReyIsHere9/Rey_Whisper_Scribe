class I18n(QObject):
    changed = Signal()

    def __init__(self, lang: str = "en") -> None:
        super().__init__()
        self._lang = lang if lang in STRINGS else "en"

    @property
    def lang(self) -> str:
        return self._lang

    @property
    def rtl(self) -> bool:
        return self._lang == "fa"

    def t(self, key: str, **values: object) -> str:
        text = STRINGS[self._lang].get(key, STRINGS["en"].get(key, key))
        if values:
            try:
                return text.format(**values)
            except (KeyError, IndexError):
                return text
        return text

    def set_lang(self, lang: str) -> None:
        if lang not in STRINGS or lang == self._lang:
            return
        self._lang = lang
        self.changed.emit()
